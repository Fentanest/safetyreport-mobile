/// 만족도(별점 사유) 조회 결과. 저장 때 별점·사유·만족도조사여부를 어떻게 다룰지 정한다(결정 D-2·D-3).
/// 서버 core/storage/reports_repo._update_title 과 같은 규칙.
enum RatingLookup {
  /// 조회하지 않음(사이트 점수 없음 등) → 기존 별점·사유 유지, '참여 완료' 는 되돌리지 않음.
