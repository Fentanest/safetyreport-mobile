  /// 조회 실패(네트워크·번호 미설정) → 사이트 점수는 쓰되 사유는 기존 유지, 미참여로 보지 않음.
  failed,

  /// 조회 성공 → 사이트 점수·사유를 그대로 기록.
  found,
}
