#!/usr/bin/env python3
"""Embed the shared JSON verbatim for synchronous Flutter/background-isolate use.

Run from any directory. --check verifies the checked-in generated file.
No asset loading, initialization order, or network dependency at runtime.
"""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / 'assets/data/traffic_fine_table.json').read_bytes()
text = source.decode('utf-8')
json.loads(text)
assert "'''" not in text
output = ("// Generated by tool/generate_traffic_fine_table.py; do not edit.\n"
          "// JSON bytes match assets/data/traffic_fine_table.json (UTF-8).\n"
          f"const trafficFineTableSha256 = '{hashlib.sha256(source).hexdigest()}';\n"
          "const trafficFineTableJson = r'''" + text + "''';\n")
target = root / 'lib/services/traffic_fine_table.g.dart'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        raise SystemExit('traffic_fine_table.g.dart is stale; run generator')
else:
    target.write_text(output, encoding='utf-8')
